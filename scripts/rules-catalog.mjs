import { mkdirSync, writeFileSync } from 'fs'
import { createRequire } from 'module'
import path from 'path'
import { fileURLToPath } from 'url'
import { ESLint } from 'eslint'

/**
 * @typedef {object} RuleSetting
 * @property {unknown[]} options - Rule options after the severity.
 * @property {string} severity - `error`, `warn`, or `off`.
 */

const loadCommonJs = createRequire(import.meta.url)
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

const severityLabels = ['off', 'warn', 'error']
const sampleTs = 'example.ts'
const sampleTsx = 'example.tsx'
const jsonIndent = 2

/**
 * Builds the rule catalog: what the config enforces, as JSON and markdown.
 *
 * @returns {Promise<{ json: string, markdown: string }>} Both texts, derived from the one resolved config.
 */
export async function buildRulesCatalog() {
	const ts = await getEffectiveRules(sampleTs)
	const tsx = await getEffectiveRules(sampleTsx)
	const tsxOnly = Object.entries(tsx).filter(([name, value]) => JSON.stringify(ts[name]) !== JSON.stringify(value))
	const catalog = { ts, tsx: Object.fromEntries(tsxOnly) }
	const rows = Object.entries(ts)
	const withSeverity = (/** @type {string} */ wanted) => rows.filter(([, { severity }]) => severity === wanted)
	const markdown = [
		'# Rule catalog',
		'',
		'Generated by `npm run docs:rules` from the resolved config for a `.ts` file. Do not edit by hand. Machine-readable: [rules.json](rules.json). Why the rules exist: [ESLINT-STANDARDS.md](ESLINT-STANDARDS.md).',
		'',
		'Rules that differ for `.tsx` files are under the `tsx` key in [rules.json](rules.json).',
		'',
		...renderGroup('Errors', withSeverity('error')),
		...renderGroup('Warnings', withSeverity('warn')),
		`Disabled: ${String(withSeverity('off').length)} rules, listed in [rules.json](rules.json).`,
		'',
	].join('\n')

	return { json: `${JSON.stringify(catalog, null, jsonIndent)}\n`, markdown }
}

/**
 * Resolves the effective rules for one sample file by running the real config through ESLint.
 *
 * @param {string} file - Sample file name that selects the config blocks to apply.
 * @returns {Promise<Record<string, RuleSetting>>} Rule name to severity and options, sorted by rule name.
 */
async function getEffectiveRules(file) {
	const { createConfig } = /** @type {{ createConfig: (options: object) => import('eslint').Linter.Config[] }} */ (
		loadCommonJs(path.join(repoRoot, 'eslint.config.js'))
	)
	const eslint = new ESLint({
		cwd: repoRoot,
		overrideConfig: createConfig({ ignores: ['dist/**'] }),
		overrideConfigFile: true,
	})
	const resolved = await eslint.calculateConfigForFile(path.join(repoRoot, file))
	const rules = /** @type {Record<string, unknown>} */ (resolved?.rules ?? {})
	/** @type {[string, RuleSetting][]} */
	const entries = Object.entries(rules).map(([name, value]) => {
		const [severity, ...options] = /** @type {unknown[]} */ (Array.isArray(value) ? value : [value])
		const label = typeof severity === 'number' ? severityLabels.at(severity) : String(severity)

		return [name, { options, severity: label ?? 'off' }]
	})

	return Object.fromEntries(entries.sort(([left], [right]) => left.localeCompare(right)))
}

/**
 * Renders one severity group as a markdown table.
 *
 * @param {string} title - Section heading.
 * @param {[string, RuleSetting][]} rows - Rule entries belonging to the group.
 * @returns {string[]} Markdown lines.
 */
function renderGroup(title, rows) {
	if (rows.length === 0) return []

	const lines = [`## ${title} (${String(rows.length)})`, '', '| Rule | Options |', '| --- | --- |']
	for (const [name, { options }] of rows) {
		const rendered = options.length === 0 ? '' : `\`${JSON.stringify(options).replaceAll('|', '\\|')}\``
		lines.push(`| \`${name}\` | ${rendered} |`)
	}

	return [...lines, '']
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const { json, markdown } = await buildRulesCatalog()
	const docs = path.join(repoRoot, 'docs')
	mkdirSync(docs, { recursive: true })
	writeFileSync(path.join(docs, 'rules.json'), json)
	writeFileSync(path.join(docs, 'RULES.md'), markdown)
}
